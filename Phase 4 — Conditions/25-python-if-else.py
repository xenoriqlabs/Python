# Python If-Else Statement

# Example 1: Check Age

age = 20

if age >= 18:
    print("You are eligible to vote.")
else:
    print("You are not eligible to vote.")


# Example 2: Check Positive or Non-Positive Number

number = -5

if number > 0:
    print("The number is positive.")
else:
    print("The number is zero or negative.")


# Example 3: Check Even or Odd

number = 7

if number % 2 == 0:
    print("The number is even.")
else:
    print("The number is odd.")


# Example 4: Check Password

password = "python123"

if password == "python123":
    print("Login successful.")
else:
    print("Incorrect password.")


# Example 5: Check Company Name

company_name = "Xenoriq Labs"

if company_name == "Xenoriq Labs":
    print("Welcome to Xenoriq Labs!")
else:
    print("Company name does not match.")


# Example 6: Check Exam Result

marks = 45

if marks >= 40:
    print("Congratulations! You passed.")
else:
    print("Sorry, you failed.")


# Example 7: Check Temperature

temperature = 35

if temperature > 30:
    print("The weather is hot.")
else:
    print("The weather is not hot.")


# Example 8: Compare Two Numbers

first_number = 15
second_number = 10

if first_number > second_number:
    print("The first number is greater.")
else:
    print("The first number is not greater.")