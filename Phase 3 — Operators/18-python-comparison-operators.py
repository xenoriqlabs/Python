# ------------------------------------------
# 1. Equal to (==)
# ------------------------------------------

x = 10
y = 10

print("x == y:", x == y)
# True


# ------------------------------------------
# 2. Not equal to (!=)
# ------------------------------------------

x = 10
y = 20

print("x != y:", x != y)
# True


# ------------------------------------------
# 3. Greater than (>)
# ------------------------------------------

x = 20
y = 10

print("x > y:", x > y)
# True


# ------------------------------------------
# 4. Less than (<)
# ------------------------------------------

x = 10
y = 20

print("x < y:", x < y)
# True


# ------------------------------------------
# 5. Greater than or equal to (>=)
# ------------------------------------------

x = 20
y = 20

print("x >= y:", x >= y)
# True


# ------------------------------------------
# 6. Less than or equal to (<=)
# ------------------------------------------

x = 10
y = 20

print("x <= y:", x <= y)
# True


# ==========================================
# Practical Example
# ==========================================

age = 18

print("\n--- Age Comparison ---")

print("Age is 18:", age == 18)
print("Age is not 20:", age != 20)
print("Age is greater than 15:", age > 15)
print("Age is less than 25:", age < 25)
print("Age is at least 18:", age >= 18)
print("Age is at most 18:", age <= 18)


# ==========================================
# Marks Example
# ==========================================

marks = 75
passing_marks = 50

print("\n--- Marks Comparison ---")

print("Marks are equal to 75:", marks == 75)
print("Marks are not equal to 40:", marks != 40)
print("Marks are greater than 50:", marks > passing_marks)
print("Marks are less than 100:", marks < 100)
print("Marks are greater than or equal to 50:", marks >= passing_marks)
print("Marks are less than or equal to 75:", marks <= 75)