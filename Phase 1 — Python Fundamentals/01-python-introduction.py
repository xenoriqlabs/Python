# 6. Interpreter

'''
A Python interpreter is the software that executes Python code.

For example, when you write:
'''
print("Hello, Word!")
'''
the Python interpreter reads and executes this code.
The interpreter allows you to run Python programs without manually converting your Python source code into machine code yourself.
'''